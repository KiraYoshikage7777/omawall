//! Язык интерфейса: русский, если Omarchy (или система) на русском, иначе английский.
use std::collections::HashMap;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::OnceLock;

static LANG: AtomicU8 = AtomicU8::new(0);

/// Перечитать язык (Omarchy хранит его в ~/.config/omarchy/language).
pub fn refresh() {
    let from_omarchy = std::fs::read_to_string(crate::config::home().join(".config/omarchy/language")).ok().map(|s| s.trim().to_lowercase()).filter(|s| !s.is_empty());
    let lang = from_omarchy.or_else(|| ["LC_ALL", "LC_MESSAGES", "LANG"].iter().find_map(|v| std::env::var(v).ok().filter(|s| !s.is_empty() && s != "C" && s != "POSIX")).map(|s| s.to_lowercase())).unwrap_or_default();
    let ru = lang.starts_with("ru") || std::env::var("OMAWALL_LANG").is_ok_and(|v| v.starts_with("ru"));
    let force_en = std::env::var("OMAWALL_LANG").is_ok_and(|v| v.starts_with("en"));
    LANG.store(if ru && !force_en { 1 } else { 2 }, Ordering::Relaxed);
}

pub fn en() -> bool {
    if LANG.load(Ordering::Relaxed) == 0 {
        refresh();
    }
    LANG.load(Ordering::Relaxed) == 2
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| EN.iter().copied().collect())
}

/// Перевод постоянной строки.
pub fn tr(s: &'static str) -> &'static str {
    if en() {
        table().get(s).copied().unwrap_or(s)
    } else {
        s
    }
}

/// Перевод строки, пришедшей из данных (названия палитр, папок).
pub fn tr_dyn(s: &str) -> String {
    if en() {
        table().get(s).map(|v| v.to_string()).unwrap_or_else(|| s.to_string())
    } else {
        s.to_string()
    }
}

#[macro_export]
macro_rules! trf {
    ($ru:literal, $en:literal $(, $a:expr)* $(,)?) => {
        if $crate::i18n::en() { format!($en $(, $a)*) } else { format!($ru $(, $a)*) }
    };
}

